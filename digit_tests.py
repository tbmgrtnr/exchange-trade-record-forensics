#!/usr/bin/env python3
"""Benford digit-test battery for one window of an exchange trade record.

Runs the full set of digit tests on the trade sizes (quantities) inside a
UTC time window of a trade archive:

* first-digit distribution vs. Benford's Law, with per-digit tests
* mantissa descriptives (mean, variance, skewness, excess kurtosis)
* mean absolute deviation (MAD) and distortion factor
* goodness-of-fit tests: Pearson chi-square, Kolmogorov-Smirnov,
  Euclidean distance, mantissa arc test
* second-order test (first digits of consecutive ordered differences)
* summation test (per-digit share of total summed quantity)

Example (the back-filled window of the Binance case study):

    python digit_tests.py data/BTCUSDT-trades-2021-05.zip \
        --start 2021-05-19T13:16 --end 2021-05-19T13:57 \
        --figdir figures

Before applying the battery elsewhere, make sure the analyzed quantity
satisfies Benford's preconditions (values spanning several orders of
magnitude, generated by a multiplicative mixture). See also README.
"""

import argparse

import numpy as np

from forensics import (BENFORD, WindowStats, chi2_test, euclid_test,
                       fmt_ms, ks_test, print_digit_table, scan_file,
                       second_order_counts, stars, summation_frequencies,
                       utc_ms)


def run_digit_tests(stats: WindowStats, figdir: str = None,
                    second_order: bool = True) -> None:
    """Print the full digit-test report for a populated WindowStats."""
    print(f"\n===== Digit-test battery: {stats.label} =====")
    print(f"Window (UTC):    {fmt_ms(stats.start_ms)} to "
          f"{fmt_ms(stats.end_ms)}")
    print(f"Observations:    {stats.n:,}")

    print_digit_table(stats.fd, "--- First-digit distribution ---")

    mm = stats.mantissa_moments()
    print("\n--- Descriptive statistics (mantissa) ---")
    print(f"{'Mean':<28}{mm['mean']:>10.3f}   (Benford: 0.500)")
    print(f"{'Variance':<28}{mm['var']:>10.3f}   (Benford: 0.083)")
    print(f"{'Ex. kurtosis':<28}{mm['ex_kurtosis']:>10.3f}   "
          f"(Benford: -1.200)")
    print(f"{'Skewness':<28}{mm['skewness']:>10.3f}   (Benford: 0.000)")
    print(f"{'Mean absolute deviation':<28}{stats.mad:>10.3f}")
    print(f"{'Distortion factor':<28}{stats.distortion_factor():>10.3f}")

    print("\n--- Goodness-of-fit tests ---")
    chi2, p_chi2 = chi2_test(stats.fd)
    ks, p_ks = ks_test(stats.fd)
    eu, p_eu = euclid_test(stats.fd)
    arc, p_arc = stats.arc_test()
    print(f"{'Pearson chi-square':<28}{chi2:>14,.0f} {stars(p_chi2)}")
    print(f"{'Kolmogorov-Smirnov':<28}{ks:>14.2f} {stars(p_ks)}")
    print(f"{'Euclidean distance':<28}{eu:>14.2f} {stars(p_eu)}")
    print(f"{'Mantissa arc test':<28}{arc:>14.2f} {stars(p_arc)}")
    print("(KS and Euclidean p-values are Monte-Carlo, 10,000 draws under "
          "the Benford null.)")

    so = None
    if second_order:
        so = second_order_counts(stats.values)
        print_digit_table(
            so, "--- Second-order test (digits of ordered differences) ---")

    sumfreq = summation_frequencies(stats.digit_qty_sum)
    print("\n--- Summation test (expected share: 11.1% per digit) ---")
    print(f"{'Digit':<22}" + "".join(f"{d:>8}" for d in range(1, 10)))
    print(f"{'Share of summed qty':<22}" +
          "".join(f"{100 * s:>7.1f}%" for s in sumfreq))

    if figdir:
        save_figures(stats, so, sumfreq, figdir)


def save_figures(stats: WindowStats, so_counts, sumfreq, figdir: str) -> None:
    """Bar-plot panels in the style of the paper's figures."""
    import os

    import matplotlib
    matplotlib.use("Agg")
    import matplotlib.pyplot as plt

    os.makedirs(figdir, exist_ok=True)
    grey, red = (0.62, 0.65, 0.69), "#E31A1C"
    digits = np.arange(1, 10)

    def bar_panel(freq, expected, fname, ylabel):
        fig, ax = plt.subplots(figsize=(6, 4))
        ax.bar(digits, 100 * freq, color=grey, edgecolor="none")
        ax.plot(digits, 100 * expected, "--", color=red, marker="o",
                markersize=4, linewidth=1.2)
        ax.set_xticks(digits)
        ax.set_xlabel("First digit")
        ax.set_ylabel(ylabel)
        ax.spines[["top", "right"]].set_visible(False)
        fig.tight_layout()
        fig.savefig(os.path.join(figdir, fname))
        plt.close(fig)

    bar_panel(stats.rel_freq, BENFORD, "digit_distribution.pdf",
              "Relative frequency (%)")
    if so_counts is not None:
        bar_panel(so_counts / so_counts.sum(), BENFORD,
                  "second_order.pdf", "Relative frequency (%)")
    bar_panel(sumfreq, np.full(9, 1 / 9), "summation.pdf",
              "Share of summed quantity (%)")

    expected_n = stats.fd.sum() * BENFORD
    contrib = (stats.fd - expected_n) ** 2 / expected_n
    fig, ax = plt.subplots(figsize=(6, 4))
    ax.bar(digits, contrib, color=grey, edgecolor="none")
    ax.set_xticks(digits)
    ax.set_xlabel("First digit")
    ax.set_ylabel("Chi-square contribution")
    ax.spines[["top", "right"]].set_visible(False)
    fig.tight_layout()
    fig.savefig(f"{figdir}/chi2_contributions.pdf")
    plt.close(fig)


def main() -> None:
    ap = argparse.ArgumentParser(
        description=__doc__,
        formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("trades", help="trade archive (CSV or ZIP)")
    ap.add_argument("--start", required=True,
                    help="window start, UTC (YYYY-MM-DDTHH:MM)")
    ap.add_argument("--end", required=True,
                    help="window end, UTC, exclusive")
    ap.add_argument("--label", default="analysis window")
    ap.add_argument("--qty-col", type=int, default=2,
                    help="0-based column of the trade quantity (default 2)")
    ap.add_argument("--time-col", type=int, default=4,
                    help="0-based column of the timestamp (default 4)")
    ap.add_argument("--time-unit", choices=["ms", "s", "us"], default="ms")
    ap.add_argument("--figdir", default=None,
                    help="write figure PDFs into this directory")
    ap.add_argument("--no-second-order", action="store_true",
                    help="skip the second-order test (saves the memory "
                         "needed to hold the window's raw values)")
    args = ap.parse_args()

    stats = WindowStats(args.label, utc_ms(args.start), utc_ms(args.end),
                        keep_values=not args.no_second_order)
    scan_file(args.trades, [stats], qty_col=args.qty_col,
              time_col=args.time_col, time_unit=args.time_unit)
    if stats.n == 0:
        raise SystemExit("no trades found in the given window")
    run_digit_tests(stats, figdir=args.figdir,
                    second_order=not args.no_second_order)


if __name__ == "__main__":
    main()
